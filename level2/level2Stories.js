// Утилита: сделать набор карточек для игры (с уникальными id)
export function buildLevel2Deck(story) {
  const mk = (text, origin) => ({
    id: `${origin}_${hash(text)}`,
    text,
    origin, // "v1" | "v2"
  });

  const v1 = story.variant1.map((t) => mk(t, "v1"));
  const v2 = story.variant2.map((t) => mk(t, "v2"));
  return shuffle([...v1, ...v2]);
}

function shuffle(arr) {
  const a = [...arr];
  for (let i = a.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [a[i], a[j]] = [a[j], a[i]];
  }
  return a;
}

function hash(s) {
  let h = 0;
  for (let i = 0; i < s.length; i++) h = (h * 31 + s.charCodeAt(i)) >>> 0;
  return h.toString(16);
}
